import { expect, test } from "@playwright/test";
import { prepareRecoveries } from "./recovery-fixtures.js";

test("full fund returns and recovered payments require independent Finance verification", async ({ browser }) => {
  test.setTimeout(180_000);
  const fixture = await prepareRecoveries(), contexts = [], errors = [];
  const ui = async email => {
    const context = await browser.newContext(); contexts.push(context);
    const page = await context.newPage(); page.on("pageerror", error => errors.push(error.message));
    await page.goto("/#/login"); await page.locator("[data-demo-login]").selectOption(email);
    await page.getByRole("button", { name: "Sign in" }).click(); await expect(page).toHaveURL(/#\/dashboard$/);
    return page;
  };
  const proof = { name: `${"ReturnReceipt".repeat(10)}.pdf`, mimeType: "application/pdf", buffer: Buffer.from("%PDF-1.4\nReturned funds evidence\n%%EOF") };
  try {
    const associate = await ui("finance.associate@payment.local"), manager = await ui("finance.manager@payment.local");
    await associate.goto(`/#/requests/${fixture.liquidation.request_number}`);
    const returned = associate.locator("[data-fund-return]");
    await returned.locator("summary").filter({ hasText: /^Record full fund return$/ }).click();
    const receipt = returned.locator("form");
    await receipt.locator('[name="recorded_on"]').fill("2026-10-15");
    await receipt.locator('[name="reference"]').fill("R".repeat(100));
    await receipt.locator('[name="receiving_office"]').fill("Finance receiving cash office");
    await receipt.locator('[name="receiving_account_id"]').selectOption(fixture.receivingAccount);
    await receipt.locator('[name="reason"]').fill("Full unused advance returned and deposited");
    await receipt.locator('[type="file"]').setInputFiles(proof);
    await associate.route("**/fund-return", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Receipt retry test" }) }));
    await receipt.getByRole("button", { name: "Record full fund return", exact: true }).click();
    await expect(receipt.getByRole("alert")).toContainText("Receipt retry test");
    await expect(receipt.locator('[name="reference"]')).toHaveValue("R".repeat(100));
    await associate.unroute("**/fund-return");
    await receipt.getByRole("button", { name: "Record full fund return", exact: true }).click();
    await expect(returned.locator("[data-fund-return-state]")).toContainText("verification pending");
    expect(Number((await fixture.get(`payments/${fixture.liquidation.id}`)).summary.fund_return_outstanding)).toBe(400);
    await manager.goto(`/#/requests/${fixture.liquidation.request_number}`);
    const review = manager.locator("[data-fund-return]");
    await review.locator("summary").filter({ hasText: /^Verify full fund return$/ }).click();
    const verification = review.locator('[data-fund-return-action="verify"]');
    await verification.locator("textarea").fill("Receipt and deposit verified independently");
    await manager.route("**/fund-return/verify", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Verification retry test" }) }));
    await verification.getByRole("button").click(); await expect(verification.getByRole("alert")).toContainText("Verification retry test");
    await manager.unroute("**/fund-return/verify");
    await verification.getByRole("button").focus(); await manager.keyboard.press("Enter");
    await expect(review.locator("[data-fund-return-state]")).toHaveText("Full fund return verified");
    await expect(review).toContainText("Verified receipt accounting");
    expect(Number((await fixture.get(`payments/${fixture.liquidation.id}`)).summary.fund_return_outstanding)).toBe(0);
    await manager.reload(); await expect(manager.locator("[data-voucher-state]")).toHaveText("Full fund return verified");
    const journal = await fixture.get(`finance-accounting/${fixture.general.id}`);
    expect(journal.saved.state).toBe("posted");
    await associate.goto(`/#/requests/${fixture.general.request_number}`);
    const card = associate.locator(`[data-payment-card="${fixture.payment}"]`);
    await card.locator("summary").filter({ hasText: /^Record full payment recovery$/ }).click();
    const recovery = card.locator('[data-payment-action="recover"]');
    await recovery.locator('[name="recorded_on"]').fill("2026-10-15");
    await recovery.locator('[name="bank_name"]').fill("Receiving Bank");
    await recovery.locator('[name="recipient_name"]').fill("Original payee");
    await recovery.locator('[name="reason"]').fill("Full transfer returned to Finance");
    await recovery.locator('[type="file"]').setInputFiles(proof);
    await associate.route("**/lines/*/recover", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Recovery retry test" }) }));
    await recovery.getByRole("button", { name: "Record full payment recovery", exact: true }).click();
    await expect(recovery.getByRole("alert")).toContainText("Recovery retry test");
    await associate.unroute("**/lines/*/recover");
    await recovery.getByRole("button", { name: "Record full payment recovery", exact: true }).click();
    await expect(card.locator("[data-payment-state]")).toContainText("Manager review pending");
    expect(Number((await fixture.get(`payments/${fixture.general.id}`)).summary.available)).toBe(0);
    await manager.goto(`/#/requests/${fixture.general.request_number}`);
    const managerCard = manager.locator(`[data-payment-card="${fixture.payment}"]`);
    await managerCard.locator("summary").filter({ hasText: /^Confirm post-release reversal$/ }).click();
    const confirm = managerCard.locator('[data-payment-action="confirm-reversal"]');
    await confirm.locator("textarea").fill("Recovery independently verified; replace payment");
    await confirm.getByRole("button").click();
    await expect(managerCard.locator("[data-payment-state]")).toContainText("Full recovery verified");
    expect(Number((await fixture.get(`payments/${fixture.general.id}`)).summary.available)).toBe(1100);
    expect((await fixture.get(`finance-accounting/${fixture.general.id}`)).saved).toEqual(journal.saved);
    await associate.reload(); await associate.getByRole("button", { name: "Prepare replacement", exact: true }).click();
    const replacement = associate.locator('[data-payment-action="prepare"]');
    await replacement.locator('[name="reference"]').fill(`REPLACED-${Date.now()}`);
    await replacement.locator('[name="reason"]').fill("Linked replacement after verified recovery");
    await replacement.getByRole("button", { name: "Prepare payment line items" }).click();
    await expect(associate.locator("[data-payment-card]")).toHaveCount(2);
    const lines = (await fixture.get(`payments/${fixture.general.id}`)).lines;
    expect(lines[1].predecessor_id).toBe(fixture.payment); expect(lines[1].state).toBe("prepared");
    const signatory = await ui("signatory@payment.local");
    await signatory.goto(`/#/requests/${fixture.general.request_number}`);
    const newCard = signatory.locator(`[data-payment-card="${lines[1].id}"]`);
    await newCard.locator("summary").filter({ hasText: /^Authorize payment line$/ }).click();
    await newCard.locator("textarea").fill("Fresh authorization for replacement");
    await newCard.getByRole("button", { name: "Authorize payment line", exact: true }).click();
    await expect(newCard.locator("[data-payment-state]")).toHaveText("Authorized");
    expect(errors).toEqual([]);
  } finally { for (const context of contexts) await context.close(); await fixture.dispose(); }
});
