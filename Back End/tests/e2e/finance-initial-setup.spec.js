import { expect, request as apiRequest, test } from "@playwright/test";

test("initial Finance setup saves progress, activates all types and records versioned review", async ({ page }) => {
  test.setTimeout(120_000);
  const api = await apiRequest.newContext({ baseURL: "http://127.0.0.1:58003" });
  const login = await api.post("/api/v1/auth/login", { data: { email: "admin@payment.local", password: "Phase01-Test-Only!" } });
  expect(login.ok()).toBeTruthy();
  const headers = { "X-CSRF-Token": (await login.json()).csrf_token };
  const accounts = [];
  for (const [account_type, normal_balance] of [["expense", "debit"], ["asset", "debit"], ["liability", "credit"], ["liability", "credit"], ["asset", "debit"]]) {
    const result = await api.post("/api/v1/chart-of-accounts", { headers, data: { code: `INI-${crypto.randomUUID().slice(0,8).toUpperCase()}`, name: `Initial setup test ${crypto.randomUUID().slice(0,8)}`, account_type, normal_balance, is_posting: true } });
    expect(result.ok(), await result.text()).toBeTruthy(); accounts.push((await result.json()).id);
  }
  const taxes = await (await api.get("/api/v1/tax-codes")).json();
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/#/login"); await page.locator("[data-demo-login]").selectOption("finance.manager@payment.local");
  await page.getByRole("button", { name: "Sign in" }).click(); await expect(page).toHaveURL(/#\/dashboard$/);
  await page.goto("/#/administration/request-settings");
  await page.getByRole("button", { name: "Start / resume initial setup" }).click();
  const guide = page.getByRole("region", { name: "Initial Finance setup", exact: true });
  await guide.getByRole("button", { name: "2. Tax rules", exact: true }).click();
  for (const [name, value] of Object.entries({ vat_basis: "inclusive", ewt_basis: "net_of_vat", rounding: "half_up", effective_date_basis: "finance_review", setup_scope: "system", tax_general: taxes.find(row => row.code === "VAT12-EWT2").id })) await guide.locator(`[name="${name}"]`).selectOption(value);
  await guide.locator('[name="effective_from"]').fill("2020-01-01");
  await guide.getByRole("button", { name: "Save setup progress" }).click();
  await expect.poll(async () => (await (await api.get("/api/v1/request-settings/finance-setup")).json()).setup_scope).toBe("system");
  await page.reload(); await page.getByRole("button", { name: "Start / resume initial setup" }).click();
  await guide.getByRole("button", { name: "2. Tax rules", exact: true }).click();
  await expect(guide.locator('[name="vat_basis"]')).toHaveValue("inclusive");
  await guide.getByRole("button", { name: "5. Activate", exact: true }).click();
  await expect(guide.locator("[data-finance-activation] button")).toBeDisabled();
  await guide.getByRole("button", { name: "3. Accounts", exact: true }).click();
  for (const [index, name] of ["debit_general", "input_vat_general", "ewt_payable_general", "credit_general", "debit_cashAdvance"].entries()) await guide.locator(`[name="${name}"]`).selectOption(accounts[index]);
  await guide.locator('[name="credit_cashAdvance"]').selectOption(accounts[3]);
  await guide.getByRole("button", { name: "4. Voucher controls", exact: true }).click();
  await guide.locator('[name="voucher_prefix"]').fill("PV");
  await guide.locator('[name="voucher_reset_basis"]').selectOption("calendar_year");
  await guide.locator('[name="voucher_certification_text"]').fill("Reviewed Finance certification");
  await page.route("**/request-settings/finance-setup", route => route.request().method() === "PUT" ? route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Save retry test" }) }) : route.continue());
  await guide.getByRole("button", { name: "Save setup progress" }).click();
  await expect(guide.locator("[data-initial-save-error]")).toContainText("Save retry test");
  await expect(guide.locator('[name="voucher_certification_text"]')).toHaveValue("Reviewed Finance certification");
  await page.unroute("**/request-settings/finance-setup");
  await guide.getByRole("button", { name: "Save setup progress" }).click();
  await expect.poll(async () => (await (await api.get("/api/v1/request-settings/finance-setup")).json()).initial_setup.configuration_ready).toBe(true);
  await guide.getByRole("button", { name: "5. Activate", exact: true }).click();
  const activation = guide.locator("[data-finance-activation]");
  await expect(activation.locator('[name="scope"]')).toHaveValue("all");
  await expect(activation.locator('[name="scope"] option')).toHaveCount(1);
  await activation.locator('[name="reason"]').fill("Synthetic initial setup activation");
  await activation.getByRole("button").click();
  await expect(activation.getByRole("button")).toHaveText("Saved version already activated");
  await guide.getByRole("button", { name: "6. Business review", exact: true }).click();
  const review = guide.locator("[data-finance-business-review]");
  await expect(review).toBeVisible();
  for (const checkbox of await review.getByRole("checkbox").all()) await checkbox.check();
  await review.locator("textarea").fill("Synthetic business acceptance only");
  await page.route("**/finance-setup/business-acceptance", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Review retry test" }) }));
  await review.getByRole("button").click(); await expect(review.getByRole("alert")).toContainText("Review retry test");
  await expect(review.locator("textarea")).toHaveValue("Synthetic business acceptance only");
  await page.unroute("**/finance-setup/business-acceptance");
  await review.getByRole("button").focus(); await page.keyboard.press("Enter");
  await expect(guide).toContainText("accepted by Carlo Mendoza");
  for (const width of [390, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
    await guide.getByRole("button", { name: "3. Accounts", exact: true }).click();
    expect(await guide.locator('[name="debit_general"]').evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThanOrEqual(42);
  }
  await page.setViewportSize({ width: 390, height: 900 });
  const dismiss = page.getByRole("button", { name: "Dismiss message" });
  if (await dismiss.isVisible()) await dismiss.click();
  expect(await guide.getByRole("button", { name: "1. Prerequisites", exact: true }).evaluate(el => el.getBoundingClientRect().width)).toBeGreaterThan(130);
  await guide.screenshot({ path: "outputs/finance-initial-setup-mobile.png" });
  await page.reload(); await expect(page.getByRole("region", { name: "Finance business acceptance" })).toContainText("Synthetic business acceptance only");
  const current = await (await api.get("/api/v1/request-settings/finance-setup")).json();
  expect(current.initial_setup.status).toBe("complete");
  const changed = await api.put("/api/v1/request-settings/finance-setup", { headers, data: { ...current, voucher: { ...current.voucher, certification_text: "Changed certification" } } });
  expect(changed.ok(), await changed.text()).toBeTruthy();
  expect((await changed.json()).initial_setup.status).toBe("changes_pending");
  await page.reload(); await expect(page.getByRole("region", { name: "Finance business acceptance" })).toContainText("Draft changes need activation");
  expect(errors).toEqual([]); await api.dispose();
});
